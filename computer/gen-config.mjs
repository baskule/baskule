#!/usr/bin/env node
// Renders opencode.template.jsonc (same directory) from env and prints the resulting config to stdout.
// Usage: node gen-config.mjs > $XDG_CONFIG_HOME/opencode/opencode.jsonc
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const dir = path.dirname(fileURLToPath(import.meta.url))
const env = process.env
const fail = (msg) => {
  console.error(`gen-config: ${msg}`)
  process.exit(1)
}

// Strip // and /* */ comments outside of strings (JSONC -> JSON).
function stripComments(src) {
  let out = ""
  for (let i = 0, inStr = false; i < src.length; i++) {
    const c = src[i]
    if (inStr) {
      out += c
      if (c === "\\") out += src[++i]
      else if (c === '"') inStr = false
    } else if (c === '"') {
      inStr = true
      out += c
    } else if (c === "/" && src[i + 1] === "/") {
      while (i < src.length && src[i] !== "\n") i++
      out += "\n"
    } else if (c === "/" && src[i + 1] === "*") {
      i = src.indexOf("*/", i + 2) + 1
      if (i === 0) fail("unterminated comment in template")
    } else out += c
  }
  return out
}

const num = (name) => {
  const v = env[name]
  if (v === undefined || v === "") return undefined
  const n = Number(v)
  if (!Number.isFinite(n)) fail(`${name} must be a number`)
  return n
}

function modelSettings() {
  const raw = env.BASKULE_LLM_MODEL_SETTINGS
  if (!raw) return null
  let v
  try {
    v = JSON.parse(raw)
  } catch {
    fail("BASKULE_LLM_MODEL_SETTINGS is not valid JSON")
  }
  if (!v || typeof v !== "object" || Array.isArray(v)) fail("BASKULE_LLM_MODEL_SETTINGS must be a JSON object")
  return Object.keys(v).length ? v : null
}

function modelCost() {
  const input = num("BASKULE_LLM_COST_INPUT")
  const output = num("BASKULE_LLM_COST_OUTPUT")
  if (input === undefined && output === undefined) return null
  const cost = { input: input ?? 0, output: output ?? 0 }
  const read = num("BASKULE_LLM_COST_CACHE_READ")
  const write = num("BASKULE_LLM_COST_CACHE_WRITE")
  if (read !== undefined || write !== undefined) cost.cache = { read, write }
  return cost
}

function modelLimit() {
  const limit = { context: num("BASKULE_LLM_CONTEXT_LIMIT"), output: num("BASKULE_LLM_OUTPUT_LIMIT") }
  return limit.context === undefined && limit.output === undefined ? null : limit
}

const computed = {
  MODEL_SETTINGS: modelSettings(),
  MODEL_COST: modelCost(),
  MODEL_LIMIT: modelLimit(),
  ASSISTANT_PROMPT: fs.readFileSync(path.join(dir, "assistant-prompt.md"), "utf8").trim(),
}
const defaults = { BASKULE_LLM_PROVIDER_NAME: "OpenAI-compatible LLM" }

let text = stripComments(fs.readFileSync(path.join(dir, "opencode.template.jsonc"), "utf8"))
text = text.replace(/"\{\{json:([A-Z_]+)\}\}"/g, (_, k) => {
  if (!(k in computed)) fail(`unknown placeholder json:${k}`)
  return JSON.stringify(computed[k])
})
text = text.replace(/\{\{env:([A-Z0-9_]+)\}\}/g, (_, k) => {
  const v = env[k] || defaults[k]
  if (v === undefined) fail(`missing env ${k}`)
  return JSON.stringify(v).slice(1, -1)
})

const dropNulls = (o) => {
  if (Array.isArray(o)) return o.map(dropNulls)
  if (o && typeof o === "object")
    return Object.fromEntries(
      Object.entries(o)
        .filter(([, v]) => v !== null && v !== undefined)
        .map(([k, v]) => [k, dropNulls(v)]),
    )
  return o
}

let config
try {
  config = dropNulls(JSON.parse(text))
} catch (e) {
  fail(`rendered template is not valid JSON: ${e.message}`)
}
process.stdout.write(
  "// GENERATED by /opt/baskule/gen-config.mjs at container start. Edits are overwritten: change env vars instead.\n" +
    JSON.stringify(config, null, 2) +
    "\n",
)
