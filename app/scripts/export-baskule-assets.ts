#!/usr/bin/env node
// @effect-diagnostics nodeBuiltinImport:off globalConsole:off -- standalone asset/code generation uses native filesystem and CLI output.
// The approved SVGs are the source for every shipped Baskule icon.
import * as NodeFSP from "node:fs/promises";
import * as NodePath from "node:path";
import sharp from "sharp";
import { encodePngIco } from "./lib/icon-export.ts";

const check = process.argv.includes("--check");
const stale: string[] = [];
async function write(file: string, data: string | Buffer) {
  if (check) {
    const current = await NodeFSP.readFile(file).catch(() => null);
    if (current === null || !current.equals(Buffer.from(data))) stale.push(file);
  } else {
    await NodeFSP.mkdir(NodePath.dirname(file), { recursive: true });
    await NodeFSP.writeFile(file, data);
  }
}
async function copy(source: string, target: string) {
  await write(target, await NodeFSP.readFile(source));
}
const root = NodePath.resolve(import.meta.dirname, "../..");
const source = NodePath.join(root, "brand");
const output = NodePath.join(root, "app/assets/baskule");

for (const name of ["wordmark", "wordmark-inverse", "icon", "symbol", "symbol-inverse"]) {
  await copy(NodePath.join(source, `${name}.svg`), NodePath.join(output, `${name}.svg`));
}
const icon = await NodeFSP.readFile(NodePath.join(source, "icon.svg"));
const png = (svg: Buffer | string, size: number) =>
  sharp(Buffer.from(svg), { density: 384 }).resize(size, size).png().toBuffer();
for (const size of [16, 32, 180, 192, 512, 1024]) {
  await write(NodePath.join(output, `icon-${size}.png`), await png(icon, size));
}
const ico = encodePngIco(
  await Promise.all(
    [16, 24, 32, 48, 64, 128, 256].map(async (size) => ({
      size,
      contents: await png(icon, size),
    })),
  ),
);
await write(NodePath.join(output, "icon.ico"), ico);
for (const name of ["wordmark", "wordmark-inverse"]) {
  await write(
    NodePath.join(output, `${name}.png`),
    await sharp(await NodeFSP.readFile(NodePath.join(source, `${name}.svg`)))
      .resize({ width: 1200 })
      .png()
      .toBuffer(),
  );
}
const symbol = await NodeFSP.readFile(NodePath.join(source, "symbol-inverse.svg"), "utf8");
const inner = symbol.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
const canvas = (size: number, fraction: number, monochrome = false) => {
  const height = size * fraction;
  const width = height * 0.7787;
  const mark = monochrome ? inner.replace(/#[0-9A-Fa-f]{6}/g, "#FFFFFF") : inner;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}"><g transform="translate(${(size - width) / 2} ${(size - height) / 2}) scale(${height / 100})">${mark}</g></svg>`;
};
// Android masks the outer third; the whole K must stay inside the safe zone.
await write(NodePath.join(output, "android-foreground.png"), await png(canvas(432, 0.56), 432));
await write(
  NodePath.join(output, "android-monochrome.png"),
  await png(canvas(432, 0.56, true), 432),
);
await write(
  NodePath.join(output, "android-notification.png"),
  await png(canvas(96, 0.8, true), 96),
);
await write(NodePath.join(output, "android-splash.png"), await png(canvas(1152, 0.3), 1152));
const publicDir = NodePath.join(root, "app/apps/web/public");
for (const [file, target] of Object.entries({
  "icon.ico": "favicon.ico",
  "icon-16.png": "favicon-16x16.png",
  "icon-32.png": "favicon-32x32.png",
  "icon-180.png": "apple-touch-icon.png",
  "icon-192.png": "icon-192.png",
  "icon-512.png": "icon-512.png",
  "icon.svg": "baskule-icon.svg",
  "wordmark.svg": "baskule-wordmark.svg",
  "wordmark-inverse.svg": "baskule-wordmark-inverse.svg",
}))
  await copy(NodePath.join(output, file), NodePath.join(publicDir, target));

await write(
  NodePath.join(root, "app/apps/server/src/mcp/baskuleIcon.ts"),
  `// Generated by export-baskule-assets.ts from brand/icon.svg.\nexport const BASKULE_MCP_ICON =\n  ${JSON.stringify("data:image/svg+xml;base64," + icon.toString("base64"))};\n`,
);
if (stale.length) throw new Error(`Stale Baskule assets:\n${stale.join("\n")}`);
console.log(
  check
    ? "Baskule assets are current."
    : "Updated Baskule web, desktop, mobile and reusable kit assets.",
);
